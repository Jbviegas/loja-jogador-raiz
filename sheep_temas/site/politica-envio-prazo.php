            <h2> Políticas de Envio e Prazo de Entrega</h2>
            <br>
            <br>

            <h3>CUIDADOS COM ENDEREÇAMENTO DE PEDIDOS</h3>
            <br>
            A loja providenciará o envio dos produtos para o endereço que o cliente solicitar. Portanto, para que não haja empecilhos para a entrega da sua encomenda, pedimos atenção no momento de preencher o endereço no qual deseja receber o seu pedido.
            <br><br>

            <h3>DESTINATÁRIO AUSENTE</h3>
            <br>
            Certifique-se de que haverá alguém no endereço para receber seus produtos. Os Correios realizam três tentativas de entrega dos produtos, caso não haja ninguém no endereço para receber a encomenda, o pacote será levado para a agência dos Correios mais próxima do endereço, e neste caso será necessário que o destinatário do pacote realize a retirada do mesmo na agência dos Correios, em até 7 dias corridos, caso o destinatário da encomenda não realize a retirada, o pacote retornará ao remetente, sendo necessário o pagamento de um novo frete para o reenvio do produto.
        
            Caso a entrega seja feita por uma empresa privada e não haja ninguém para receber a encomenda, a encomenda retornará para o local onde a empresa contratada para fazer o frete armazena as encomendas dos clientes, e de acordo com as normas da empresa contratada o produto poderá ser retirado no local onde ele foi armazenado, ser devolvido ao remetente, ou a empresa contratada para fazer o frete poderá fazer uma nova tentativa de entrega.

            Todos os detalhes relacionados às tentativas de entrega, bem como o endereço da empresa privada contratada para fazer o frete, bem como da agência dos Correios na qual o destinatário deverá buscar seu pacote no caso de ausência no endereço, ficam registrados no rastreio do pedido, que pode ser acompanhado no site dos Correios, utilizando o código de rastreio fornecido pela Loja.
            <br><br>

            <h3>ENDEREÇO INCORRETO OU INCOMPLETO</h3>
            <br>
            A loja não se responsabiliza pelo preenchimento incorreto ou incompleto do endereço de destino dos pedidos realizados na loja. Caso ocorra o endereçamento incorreto ou incompleto , o pacote retornará ao remetente, e não serão mais realizadas outras tentativas de entrega naquele endereço.

            Em caso da entrega não ser realizada devido a divergência no endereço informado pelo cliente, o cliente não tem direito ao reembolso, será necessário o pagamento de um novo frete para reenvio do produto.
            <br><br>

            <h3>PRAZO DE PROCESSAMENTO</h3>
            <br>
            Após seu pedido ser processado e o pagamento cair em nosso sistema, os próximos passos são: separação, embalagem e despacho. Este processo geralmente leva cerca de 48 horas.

            Você receberá o código de rastreamento no painel do cliente em até 7 dias úteis após o processamento do seu pedido.
            <br><br>

            <h3>PRAZO DE ENTREGA</h3>
            <br>
            O prazo de entrega é estimado de 5 a 15 dias úteis após a confirmação do pagamento.

            Todavia, fatores adversos tais como greve dos Correios, impossibilidade de entrega devido a fatores climáticos ou áreas de risco, feriados nacionais podem acrescer alguns dias na entrega do produto.

            Entretanto, o prazo de garantia máximo é de 60 dias úteis.
            <br><br>

            <h3>FORMAS DE ENVIO</h3>
            <br>
            Os produtos são entregues pelos Correios ou empresas privadas, no entanto, em alguns casos tais como destinatário ausente, região com limitação de entrega ou até endereço incorreto, pode ser que o cliente tenha que buscar o produto na agência mais próxima a sua residência.

            Caso o endereço não seja preenchido corretamente, é possível que o produto retorne ao remetente. Pedimos atenção redobrada na hora de preencher o endereço. Caso haja algum erro no preenchimento do endereço e o produto não possa ser entregue, a responsabilidade é do cliente.
            <br><br>

