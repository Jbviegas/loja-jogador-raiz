            <h2> Políticas de Privacidade</h2>
            <br>
            <br>

            A loja assume o compromisso referente a privacidade e segurança de seus clientes durante todo o processo de navegação e compra pelo site. Dados cadastrais como nome, telefone, endereço e CPF nunca serão vendidos ou disponibilizados para terceiros, exceto quando essas informações são obrigatórias para o processo de entrega e cobrança. Os dados pessoais são fundamentais para que seu pedido chegue em segurança na sua casa e de acordo com o prazo de entrega dimensionado em nosso site.

            Você sabe o que é a LGPD?<br>

            A Lei Geral de Proteção de Dados (Lei nº 13.709/2018), tem como objetivo protocolar o tratamento de dados pessoais de clientes e usuários por parte de empresas que atuam no segmento público e privado.
            <br>
            Você sabe o que são cookies?
            <br>
            Se referem a pequenos arquivos de texto (cookies) enviados para seu navegador, contendo registros sobre seu comportamento ao acessar um site. Utilizamos cookies para reconhecer o seu navegador ou dispositivo, aprender mais sobre seus interesses referente aos produtos catalogados em nossa plataforma,
            <br>
            Cookies Primários
            <br>
            Utilizamos cookies primários, este tipo de cookie é emitido pelo domínio da loja geralmente são utilizados para identificar preferências de idioma e local ou facilitar a funcionalidade básica do site.
            <br>
            Cookies da Sessão
            <br>
            Cookies da sessão são cookies que ficam ativos de forma temporária e que são utilizados apenas para lembrar de você durante o curso da sua visita em nosso site. Este tipo de cookie perde a validade quando você fecha o navegador.
            <br>
            Cookies Persistentes
            <br>
            Cookies persistentes são utilizados para lembrar suas preferências do site e permanecem no seu desktop ou dispositivo móvel mesmo depois de você fechar o seu navegador ou efetuar uma reinicialização. Estes cookies são utilizados para fazer uma analise do comportamento do usuário e estabelecer padrões, de modo que possamos melhorar a funcionalidade do site para você e outros que visitam o site.
            <br>
            Como os Cookies de terceiros são usados?
            <br>
            Para algumas das funções dentro do nosso site usamos fornecedores terceirizados, por exemplo, quando você visita uma página com um vídeo incorporado ou proveniente do YouTube. Estes vídeos ou links (e qualquer outro conteúdo de fornecedores terceirizados) podem conter cookies de terceiros, e nós recomendamos consultar as políticas de privacidade destes terceiros no seu site para informações relativas à sua utilização de cookies.
            <br>
            O Usuário está ciente de que fornece informação de forma consciente e voluntária. Quando o Usuário realiza o cadastro, os Dados Pessoais solicitados serão mantidos em sigilo e serão utilizados apenas para o propósito de envio do produto até a casa do cliente.
            <br>
            A loja utiliza cookies e informações de sua navegação (sessão do browser) com o objetivo de traçar um perfil do público que visita o site e aperfeiçoar sempre nossos serviços, produtos, conteúdos e garantir as melhores ofertas e promoções para você. Durante todo este processo mantemos suas informações em sigilo absoluto. Vale lembrar que seus dados são registrados pelo site de forma automatizada, dispensando manipulação humana.
